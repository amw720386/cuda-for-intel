#!/usr/bin/env python3
"""Generate docs/api-coverage.md: reference API symbols vs what the shim exports.

Reference lists live in scripts/api_reference/ (names scraped from the public CUDA
headers / NVML / cuFFT / cuSPARSE / cuBLAS bindings, plus the import table of a real
torch_cuda.dll dumped with scripts/pe_imports.py).
Status per symbol: implemented | stub (exported, returns a fixed error) | missing.
usage: api_audit.py [--check]   (--check exits 1 if docs/api-coverage.md is stale)
"""
import re, sys, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
ref = root / "scripts" / "api_reference"

FN = re.compile(r'#\[(?:unsafe\()?no_mangle\)?\]\s*(?:#\[[^\]]*\]\s*)*pub\s+(?:unsafe\s+)?extern\s+"[a-zA-Z-]+"\s+fn\s+(\w+)\s*\(', re.S)
# body that is a single constant / error expression => stub
STUB_BODY = re.compile(r'^(?:return\s+)?(?:[A-Za-z_][\w:]*|-?\d+)(?:\s+as\s+\w+)?\s*;?$')

def body_after(text, pos):
    i = text.index("{", text.index(")", pos)) if "{" in text[pos:] else -1
    # skip the return type up to the first '{' after the parameter list
    depth = 0; j = pos
    # find end of param list
    p = text.index("(", pos); d = 0
    while True:
        c = text[p]
        d += c == "("; d -= c == ")"
        p += 1
        if d == 0: break
    b = text.index("{", p)
    depth = 0; k = b
    while True:
        c = text[k]
        depth += c == "{"; depth -= c == "}"
        k += 1
        if depth == 0: break
    return text[b + 1:k - 1].strip()

def scan(dirs):
    out = {}
    for d in dirs:
        for p in sorted((root / d).rglob("*.rs")):
            t = p.read_text()
            for m in FN.finditer(t):
                body = body_after(t, m.start())
                body = re.sub(r"//[^\n]*", "", body).strip()
                stub = bool(STUB_BODY.match(body)) or "NOT_SUPPORTED" in body and len(body) < 90 and "(" not in body.replace("set_error(", "")
                name = m.group(1)
                # an implemented definition wins over a stub duplicate
                out[name] = out.get(name, True) and stub
    return out  # name -> is_stub

INTEROP = re.compile(r"^(cuD3D|cuGL|cuEGL|cuVDPAU|cuGraphics(D3D|GL|EGL|VDPAU)|cuEventCreateFromEGLSync|cuWGL|cuCheckpoint|cuCoredump)")
def klass(n, refset):
    """core | interop (graphics API interop, checkpoint) | ptsz (per-thread-stream alias) | legacy (unversioned alias of a _vN symbol)"""
    if INTEROP.match(n): return "interop"
    if n.endswith(("_ptsz", "_ptds")): return "ptsz"
    if any(f"{n}_v{i}" in refset for i in range(2, 6)): return "legacy"
    return "core"

def names(f):
    p = ref / f
    return [l.strip() for l in p.read_text().split() if l.strip()] if p.exists() else []

torch = {}
for l in (ref / "torch_cuda_dll_imports.tsv").read_text().splitlines():
    dll, sym = l.split("\t")
    torch.setdefault(dll.split("64_")[0].split("64")[0] if False else dll, set()).add(sym)
def torch_for(prefix):
    s = set()
    for dll, syms in torch.items():
        if dll.startswith(prefix): s |= syms
    return s

LIBS = [
 ("CUDA driver API (cuda.h)", "driver.txt", ["src"], None, "nvcuda"),
 ("CUDA runtime API (cuda_runtime_api.h)", "runtime.txt", ["crates/cudart_shim/src"], "cudart", "cudart64_12"),
 ("cuBLAS", "cublas.txt", ["crates/cublas_shim/src"], "cublas64", "cublas64_12"),
 ("cuBLASLt", "cublaslt.txt", ["crates/cublas_shim/src"], "cublaslt", "cublas64_12 (cublasLt*)"),
 ("NVML", "nvml.txt", ["crates/nvml_shim/src"], None, "nvml"),
 ("cuFFT", "cufft.txt", ["crates/cufft_shim/src"], "cufft", "cufft64_11"),
 ("cuSPARSE", "cusparse.txt", ["crates/cusparse_shim/src"], "cusparse", "cusparse64_12"),
 ("cuSOLVER", None, ["crates/cusolver_shim/src"], "cusolver", "cusolver64_11"),
]

def main():
    lines = ["# API coverage", "",
      "Generated by `scripts/api_audit.py` (do not edit by hand). Reference symbol lists are in",
      "`scripts/api_reference/`: runtime API from the public `cuda_runtime_api.h` (12.9), the",
      "driver, NVML, cuFFT, cuSPARSE, cuBLAS and cuBLASLt lists from public header bindings, and",
      "the 'real app' column from the import table of a real `torch_cuda.dll` (conda-forge",
      "libtorch 2.13 cuda128; dump with `scripts/pe_imports.py`).", "",
      "Status: **implemented** = real behaviour; **stub** = exported, returns a fixed error code",
      "(never panics/aborts); **missing** = not exported (the loader fails the import).", "",
      "Not exported on purpose (class column): graphics-API interop (`cuD3D*`, `cuGL*`, `cuEGL*`,",
      "`cuVDPAU*`, checkpoint, coredump), per-thread-stream `_ptsz`/`_ptds` aliases and unversioned",
      "legacy aliases of `_vN` symbols (drivers resolve those through `cuGetProcAddress`).", "",
      "Behaviour notes for the entry points that are not plain forwards:", "",
      "- Unsupported surfaces return the library's own NOT_SUPPORTED status (driver/runtime 801, cuBLAS 15,",
      "  NVML 3, cuFFT 16, cuSPARSE 10, cuSOLVER 9). Stub files are generated by `scripts/gen_api_stubs.py`.",
      "- NVML answers device count, name, UUID, PCI id, memory, compute capability and driver versions from",
      "  the Driver API; sensors, clocks, power, ECC and process lists return NOT_SUPPORTED (process lists are empty).",
      "- `cuLaunchCooperativeKernel` / `cudaLaunchCooperativeKernel` launch only grids that fit the resident-block",
      "  capacity (occupancy x multiprocessors) and otherwise fail with `COOPERATIVE_LAUNCH_TOO_LARGE` (720).",
      "  The device attribute stays 0, so well-behaved applications never take this path. Not yet verified on hardware.",
      "- Stream priority has one level; `cuStreamGetPriority` reports 0. Context limits and cache/shared-memory",
      "  configuration are stored per context and have no effect on the backend.",
      "- `cudaMallocAsync`/`cudaFreeAsync` allocate immediately and drain the stream on free (valid stream order).",
      "  Memory pools (`cudaMemPool*`) and managed memory remain NOT_SUPPORTED.",
      "- `cublasSgemv_v2` (unit strides) and `cublasSdot_v2` (host pointer mode, unit strides) are expressed as",
      "  GEMM calls on the verified GEMM path; strided variants return NOT_SUPPORTED.", "",
      "## Summary", "",
      "| Library | Reference symbols | Implemented | Stub | Missing | of which core | Torch imports (impl/stub/missing) |",
      "|---|---|---|---|---|---|---|"]
    detail = []
    for title, rf, dirs, tprefix, dll in LIBS:
        exp = scan(dirs)
        t = torch_for(tprefix) if tprefix else set()
        if tprefix == "cublas64": t = {s for s in t if not s.startswith("cublasLt")}
        if tprefix == "cublaslt": t = {s for s in t if s.startswith("cublasLt")} | torch_for("cublaslt")
        if tprefix == "cublaslt": tprefix = None
        ref_names = names(rf) if rf else sorted(t)
        if tprefix == "cublas64" or title == "cuBLAS": ref_names = [n for n in ref_names if not n.startswith("cublasLt")]
        if title == "cuBLASLt": ref_names = [n for n in ref_names if n.startswith("cublasLt")]
        ref_set = set(ref_names) | t
        def st(n): return "missing" if n not in exp else ("stub" if exp[n] else "implemented")
        cnt = {"implemented": 0, "stub": 0, "missing": 0}
        tc = {"implemented": 0, "stub": 0, "missing": 0}
        rows = []; core_missing = 0
        for n in sorted(ref_set):
            s = st(n); cnt[s] += 1
            if s == "missing" and klass(n, ref_set) == "core": core_missing += 1
            if n in t: tc[s] += 1
            rows.append((n, s, "yes" if n in t else "", klass(n, ref_set)))
        extra = sorted(set(exp) - ref_set)
        lines.append(f"| {title} | {len(ref_set)} | {cnt['implemented']} | {cnt['stub']} | {cnt['missing']} | {core_missing} | {len(t)} ({tc['implemented']}/{tc['stub']}/{tc['missing']}) |")
        detail += ["", f"## {title}", "",
                   f"Binary: `{dll}`. Exported but not in the reference list: {len(extra)}"
                   + (" (" + ", ".join(f"`{e}`" for e in extra[:40]) + (" ..." if len(extra) > 40 else "") + ")" if extra else "") + ".", "",
                   "| Symbol | Status | Class | Imported by real torch_cuda |", "|---|---|---|---|"]
        detail += [f"| `{n}` | {s} | {k} | {a} |" for n, s, a, k in rows]
    out = "\n".join(lines + detail) + "\n"
    target = root / "docs" / "api-coverage.md"
    if "--check" in sys.argv:
        sys.exit(0 if target.exists() and target.read_text() == out else 1)
    target.write_text(out)
    print("\n".join(lines))

main()
