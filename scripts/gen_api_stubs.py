#!/usr/bin/env python3
"""Generate exported NOT_SUPPORTED stubs so a library exports its whole public surface.

usage: gen_api_stubs.py <driver|cudart|nvml|cufft|cusparse|cusolver>   (run from repo root)

Every symbol in the reference list (scripts/api_reference) or imported by a real
torch_cuda.dll that the crate does not already implement gets
`pub extern "system" fn name() -> i32 { <library NOT_SUPPORTED code> }`.
Arguments are ignored: on x86-64 the caller owns the stack, so the extra arguments are
harmless, and returning a status code never aborts the process.
"""
import re, sys, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
ref = root / "scripts" / "api_reference"
FN = re.compile(r'#\[(?:unsafe\()?no_mangle\)?\]\s*(?:#\[[^\]]*\]\s*)*pub\s+(?:unsafe\s+)?extern\s+"[a-zA-Z-]+"\s+fn\s+(\w+)', re.S)
INTEROP = re.compile(r"^(cuD3D|cuGL|cuEGL|cuVDPAU|cuGraphics(D3D|GL|EGL|VDPAU)|cuEventCreateFromEGLSync|cuWGL|cuCheckpoint|cuCoredump)")

def torch(prefix):
    out = set()
    for l in (ref / "torch_cuda_dll_imports.tsv").read_text().splitlines():
        dll, sym = l.split("\t")
        if dll.startswith(prefix): out.add(sym)
    return out

def names(f):
    return set((ref / f).read_text().split())

# kind -> (reference names, source dir, stub file, not-supported code, excluded names, doc)
def spec(kind):
    if kind == "driver":
        n = names("driver.txt")
        sib = lambda x: any(f"{x}_v{i}" in n for i in range(2, 6))
        # legacy unversioned aliases and per-thread-stream variants are not exported
        n = {x for x in n if not INTEROP.match(x) and not x.endswith(("_ptsz", "_ptds")) and not sib(x)}
        return n, "src", "src/cuda/stubs.rs", 801, set(), "CUDA_ERROR_NOT_SUPPORTED"
    if kind == "cudart":
        n = names("runtime.txt") | {s for s in torch("cudart") if s.startswith("cuda")}
        return n, "crates/cudart_shim/src", "crates/cudart_shim/src/stubs.rs", 801, {"cudaCreateChannelDesc", "cudaGetErrorString", "cudaGetErrorName"}, "cudaErrorNotSupported"
    if kind == "nvml":
        return names("nvml.txt"), "crates/nvml_shim/src", "crates/nvml_shim/src/stubs.rs", 3, set(), "NVML_ERROR_NOT_SUPPORTED"
    if kind == "cufft":
        return names("cufft.txt") | torch("cufft"), "crates/cufft_shim/src", "crates/cufft_shim/src/stubs.rs", 16, set(), "CUFFT_NOT_SUPPORTED"
    if kind == "cusparse":
        return names("cusparse.txt") | torch("cusparse"), "crates/cusparse_shim/src", "crates/cusparse_shim/src/stubs.rs", 10, {"cusparseGetErrorName", "cusparseGetErrorString"}, "CUSPARSE_STATUS_NOT_SUPPORTED"
    if kind == "cusolver":
        return torch("cusolver"), "crates/cusolver_shim/src", "crates/cusolver_shim/src/stubs.rs", 9, set(), "CUSOLVER_STATUS_NOT_SUPPORTED"
    sys.exit(__doc__)

kind = sys.argv[1] if len(sys.argv) > 1 else ""
wanted, src, target, code, skip, doc = spec(kind)
impl = set()
for p in (root / src).rglob("*.rs"):
    if p == root / target: continue
    impl |= set(FN.findall(p.read_text()))
todo = sorted(x for x in wanted - impl - skip if re.match(r"^[A-Za-z_]\w*$", x))
out = [f"//! Generated by scripts/gen_api_stubs.py {kind}. Do not edit.",
       f"//! Every name below returns {doc} ({code}); implemented entry points live elsewhere.",
       "#![allow(non_snake_case)]", ""]
for x in todo:
    ret = "u32" if kind == "nvml" else "i32"
    out.append(f'#[unsafe(no_mangle)]\npub extern "system" fn {x}() -> {ret} {{ {code} }}')
(root / target).write_text("\n".join(out) + "\n")
print(kind, len(todo), "stubs")
