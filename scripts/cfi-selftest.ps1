<#
.SYNOPSIS
  Runs a small vector add (PTX -> SPIR-V -> Level Zero) through the shim and prints PASS or FAIL.

.DESCRIPTION
  Loads <BinDir>\nvcuda.dll by full path, then calls the CUDA Driver API: cuInit, device query,
  cuModuleLoadData with a vector_add PTX, a launch of 1024 elements and a result check.
  The work runs in a child job with a timeout so a hang cannot freeze your shell.
  Uses the GPU for a second or two (the first kernel compile can take longer).
  On a shared machine, take your GPU lock before running this.
  Exit code: 0 PASS, 1 FAIL, 2 prerequisites missing.

.PARAMETER BinDir
  Directory holding nvcuda.dll (default: <install dir>\bin).
.PARAMETER TimeoutSec
  Give up after this many seconds (default 300).
#>
[CmdletBinding()]
param([string]$BinDir, [string]$InstallDir, [int]$TimeoutSec = 300)
$ErrorActionPreference = 'Stop'
. (Join-Path $PSScriptRoot 'cfi-common.ps1')
if (-not $InstallDir) { $InstallDir = Get-CfiDefaultInstallDir }
if (-not $BinDir) { $BinDir = Join-Path $InstallDir 'bin' }
$dll = Join-Path $BinDir 'nvcuda.dll'

function Fail([string]$why, [string]$next) {
    Write-Host 'SELFTEST: FAIL'
    Write-Safe "  reason:    $why"
    Write-Safe "  next step: $next"
    Write-Host '  then run:  pwsh -File scripts\cfi-doctor.ps1   and attach the output to an issue.'
    exit 1
}

if (-not (Test-Path -LiteralPath $dll -PathType Leaf)) {
    Write-Safe "SELFTEST: SKIPPED, shim not found at $dll"
    Write-Host '  next step: pwsh -File scripts\cfi.ps1 install'
    exit 2
}
if (-not (Find-LevelZeroLoader)) {
    Write-Host 'SELFTEST: SKIPPED, Level Zero loader (ze_loader.dll) not found'
    Write-Host '  next step: install or update the Intel graphics driver, then rerun.'
    exit 2
}

$ptx = @'
//
// Generated by LLVM NVPTX Back-End
//

.version 4.1
.target sm_52
.address_size 64

.visible .entry vector_add(
	.param .u64 .ptr .align 1 vector_add_param_0,
	.param .u64 .ptr .align 1 vector_add_param_1,
	.param .u64 .ptr .align 1 vector_add_param_2,
	.param .u32 vector_add_param_3
)
{
	.reg .pred 	%p<2>;
	.reg .b32 	%r<9>;
	.reg .b64 	%rd<11>;

	ld.param.b64 	%rd4, [vector_add_param_0];
	ld.param.b64 	%rd5, [vector_add_param_2];
	cvta.to.global.u64 	%rd6, %rd5;
	ld.param.b64 	%rd7, [vector_add_param_1];
	cvta.to.global.u64 	%rd8, %rd7;
	cvta.to.global.u64 	%rd9, %rd4;
	ld.param.b32 	%r1, [vector_add_param_3];
	mov.u32 	%r2, %ctaid.x;
	mov.u32 	%r3, %ntid.x;
	mov.u32 	%r4, %tid.x;
	mad.lo.s32 	%r5, %r2, %r3, %r4;
	setp.ge.u32 	%p1, %r5, %r1;
	@%p1 bra 	$L__BB0_2;
	mul.wide.u32 	%rd10, %r5, 4;
	add.s64 	%rd1, %rd6, %rd10;
	add.s64 	%rd2, %rd8, %rd10;
	add.s64 	%rd3, %rd9, %rd10;
	ld.global.b32 	%r6, [%rd3];
	ld.global.b32 	%r7, [%rd2];
	add.f32 	%r8, %r6, %r7;
	st.global.b32 	[%rd1], %r8;
$L__BB0_2:
	ret;
}
'@

$cs = @'
using System;
using System.Runtime.InteropServices;
using System.Text;
public static class CfiSelfTest {
    [DllImport("kernel32", CharSet = CharSet.Unicode, SetLastError = true)] static extern IntPtr LoadLibraryW(string p);
    const string D = "nvcuda.dll";
    [DllImport(D)] static extern int cuInit(uint f);
    [DllImport(D)] static extern int cuDeviceGetCount(out int n);
    [DllImport(D)] static extern int cuDeviceGet(out int dev, int ordinal);
    [DllImport(D)] static extern int cuDeviceGetName(byte[] name, int len, int dev);
    [DllImport(D)] static extern int cuCtxCreate_v2(out IntPtr ctx, uint flags, int dev);
    [DllImport(D)] static extern int cuCtxDestroy_v2(IntPtr ctx);
    [DllImport(D)] static extern int cuModuleLoadData(out IntPtr mod, byte[] image);
    [DllImport(D)] static extern int cuModuleGetFunction(out IntPtr f, IntPtr mod, string name);
    [DllImport(D)] static extern int cuMemAlloc_v2(out ulong p, UIntPtr bytes);
    [DllImport(D)] static extern int cuMemFree_v2(ulong p);
    [DllImport(D)] static extern int cuMemcpyHtoD_v2(ulong d, float[] h, UIntPtr bytes);
    [DllImport(D)] static extern int cuMemcpyDtoH_v2(float[] h, ulong d, UIntPtr bytes);
    [DllImport(D)] static extern int cuLaunchKernel(IntPtr f, uint gx, uint gy, uint gz, uint bx, uint by, uint bz,
        uint shared, IntPtr stream, IntPtr[] args, IntPtr extra);
    [DllImport(D)] static extern int cuCtxSynchronize();

    static string Step;
    static void Check(int rc, string step) { Step = step; if (rc != 0) throw new Exception(step + " returned " + rc); }

    public static string Run(string dllPath, string ptx) {
        if (LoadLibraryW(dllPath) == IntPtr.Zero) return "FAIL|LoadLibrary failed, win32 error " + Marshal.GetLastWin32Error() + "|Install the Microsoft Visual C++ x64 redistributable and rerun.";
        try {
            Check(cuInit(0), "cuInit");
            int n; Check(cuDeviceGetCount(out n), "cuDeviceGetCount");
            if (n < 1) return "FAIL|no devices reported by the shim|Install or update the Intel graphics driver; remote desktop and VMs without GPU passthrough expose no GPU.";
            int dev; Check(cuDeviceGet(out dev, 0), "cuDeviceGet");
            byte[] nm = new byte[256]; Check(cuDeviceGetName(nm, 256, dev), "cuDeviceGetName");
            string name = Encoding.ASCII.GetString(nm).TrimEnd('\0');
            IntPtr ctx; Check(cuCtxCreate_v2(out ctx, 0, dev), "cuCtxCreate");
            IntPtr mod; byte[] img = Encoding.ASCII.GetBytes(ptx + "\0");
            Check(cuModuleLoadData(out mod, img), "cuModuleLoadData (PTX translation)");
            IntPtr fn; Check(cuModuleGetFunction(out fn, mod, "vector_add"), "cuModuleGetFunction");
            const int N = 1024;
            float[] a = new float[N], b = new float[N], c = new float[N];
            for (int i = 0; i < N; i++) { a[i] = i; b[i] = 2 * i + 1; }
            UIntPtr bytes = (UIntPtr)(N * 4);
            ulong da, db, dc;
            Check(cuMemAlloc_v2(out da, bytes), "cuMemAlloc"); Check(cuMemAlloc_v2(out db, bytes), "cuMemAlloc"); Check(cuMemAlloc_v2(out dc, bytes), "cuMemAlloc");
            Check(cuMemcpyHtoD_v2(da, a, bytes), "cuMemcpyHtoD"); Check(cuMemcpyHtoD_v2(db, b, bytes), "cuMemcpyHtoD");
            GCHandle h1 = GCHandle.Alloc(da, GCHandleType.Pinned), h2 = GCHandle.Alloc(db, GCHandleType.Pinned),
                     h3 = GCHandle.Alloc(dc, GCHandleType.Pinned), h4 = GCHandle.Alloc(N, GCHandleType.Pinned);
            try {
                IntPtr[] args = { h1.AddrOfPinnedObject(), h2.AddrOfPinnedObject(), h3.AddrOfPinnedObject(), h4.AddrOfPinnedObject() };
                Check(cuLaunchKernel(fn, N / 256, 1, 1, 256, 1, 1, 0, IntPtr.Zero, args, IntPtr.Zero), "cuLaunchKernel");
                Check(cuCtxSynchronize(), "cuCtxSynchronize");
            } finally { h1.Free(); h2.Free(); h3.Free(); h4.Free(); }
            Check(cuMemcpyDtoH_v2(c, dc, bytes), "cuMemcpyDtoH");
            int bad = 0;
            for (int i = 0; i < N; i++) if (c[i] != a[i] + b[i]) bad++;
            cuMemFree_v2(da); cuMemFree_v2(db); cuMemFree_v2(dc); cuCtxDestroy_v2(ctx);
            if (bad != 0) return "FAIL|" + bad + " of " + N + " results wrong on " + name + "|This is a correctness bug. Collect the doctor output and open an issue.";
            return "PASS|" + name + "|" + N + " elements correct";
        } catch (Exception e) {
            string hint = "Run again with CUDA_FOR_INTEL_LOG=1 and CUDA_FOR_INTEL_TRACE=1 and attach the output.";
            if (e.Message.Contains("returned 100") || e.Message.Contains("returned 3")) hint = "No usable Intel GPU via Level Zero. Update the Intel graphics driver and check Device Manager.";
            if (e.Message.Contains("returned 218")) hint = "The translator rejected this PTX. Please open an issue with the doctor output.";
            if (e.Message.Contains("returned 719")) hint = "Device lost (likely a driver timeout). Close other GPU programs and retry.";
            return "FAIL|" + e.Message + "|" + hint;
        }
    }
}
'@

$job = Start-Job -ScriptBlock {
    param($dllPath, $ptxText, $source)
    Add-Type -TypeDefinition $source
    [CfiSelfTest]::Run($dllPath, $ptxText)
} -ArgumentList $dll, $ptx, $cs
if (-not (Wait-Job $job -Timeout $TimeoutSec)) {
    Stop-Job $job -ErrorAction SilentlyContinue
    Remove-Job $job -Force -ErrorAction SilentlyContinue
    Fail "no answer after $TimeoutSec seconds (first-time kernel compilation, or a hung driver)" 'Wait and rerun once (the compile is cached), or reboot if the GPU is stuck.'
}
$out = @(Receive-Job $job -ErrorAction SilentlyContinue)
Remove-Job $job -Force -ErrorAction SilentlyContinue
$line = $out | Where-Object { $_ -is [string] -and $_ -match '^(PASS|FAIL)\|' } | Select-Object -Last 1
if (-not $line) { Fail 'self-test process produced no result (crashed?)' 'Install the VC++ x64 redistributable; update the Intel driver; rerun.' }
$parts = $line.Split('|')
if ($parts[0] -eq 'PASS') {
    Write-Safe "SELFTEST: PASS  ($($parts[1]); $($parts[2]))"
    exit 0
}
Fail $parts[1] $parts[2]
