"""Regenerate the Milestone 15 PTX fixture from the pinned llama.cpp checkout."""
import argparse
from pathlib import Path
import re
import subprocess
import tempfile

REVISION = "52e53a76df0298d2c316ae7e704eeec03b0bf478"
ENTRIES = {
    "scale": "_Z9scale_f32IfEvPKT_PS0_ffj5uint3S4_S4_jjjjjj",
    "clamp": "_Z15op_clamp_kernelIfEvPKT_PS0_S0_S0_j5uint3S4_S4_jjjjjj",
}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("llama_cpp", type=Path)
    parser.add_argument("--nvcc", default="nvcc")
    parser.add_argument("--output", type=Path, default=Path("examples/ggml_scale_clamp.ptx"))
    args = parser.parse_args()
    root = args.llama_cpp.resolve() / "ggml"
    if (args.llama_cpp / ".git").exists():
        head = subprocess.check_output(
            ["git", "-C", args.llama_cpp, "rev-parse", "HEAD"], text=True
        ).strip()
        if head != REVISION:
            parser.error(f"expected llama.cpp {REVISION}, got {head}")

    header = None
    entries = []
    with tempfile.TemporaryDirectory() as tmp:
        for unit, symbol in ENTRIES.items():
            output = Path(tmp) / f"{unit}.ptx"
            subprocess.run([
                args.nvcc, "-std=c++17", "-O3", "--ptx", "-arch=compute_80",
                "-DGGML_CUDA_NO_VMM", "-I", root / "include", "-I", root / "src",
                root / "src" / "ggml-cuda" / f"{unit}.cu", "-o", output,
            ], check=True)
            source = output.read_text(encoding="ascii")
            current_header = re.search(r"\A.*?^\.address_size 64$", source, re.M | re.S)
            entry = re.search(rf"^\.entry {re.escape(symbol)}\(\n.*?^\}}$", source, re.M | re.S)
            if not current_header or not entry:
                parser.error(f"unexpected nvcc output for {unit}.cu")
            if header is not None and header != current_header[0]:
                parser.error(f"mismatched PTX header for {unit}.cu")
            header = current_header[0]
            # Exclude unrelated translation-unit globals and other specializations.
            entries.append(entry[0])

    text = (
        f"// Unmodified FP32 entries from GGML scale.cu and clamp.cu at {REVISION}.\n"
        "// Copyright (c) 2023-2026 The ggml authors. See ggml-LICENSE.\n"
        "// Generated by scripts/build-ggml-ptx.py.\n"
        + "\n\n".join([header, *entries]) + "\n"
    )
    args.output.write_text(text, encoding="ascii", newline="\n")


if __name__ == "__main__":
    main()
