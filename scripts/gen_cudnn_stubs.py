#!/usr/bin/env python3
"""Regenerate crates/cudnn_shim/src/stubs.rs.

Every cuDNN entry point of the v8 and v9 headers that lib.rs does not implement
is exported as a stub returning CUDNN_STATUS_NOT_SUPPORTED. Windows x64 (and
SysV) pass arguments in registers, so a stub needs no parameter list.

Usage: gen_cudnn_stubs.py <path to zluda cuda_macros/src (cudnn8.rs, cudnn9.rs)>
"""
import re, sys, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
macros = pathlib.Path(sys.argv[1])
names = set()
for f in ("cudnn8.rs", "cudnn9.rs"):
    names |= set(re.findall(r"fn (cudnn\w+)\(", (macros / f).read_text()))
lib = (root / "crates/cudnn_shim/src/lib.rs").read_text()
implemented = set(re.findall(r'pub unsafe extern "system" fn (cudnn\w+)', lib))
implemented |= set(re.findall(r"version_checks!\(([^)]*)\)", lib, re.S) and
                   re.findall(r"cudnn\w+", re.search(r"version_checks!\(([^)]*)\)", lib, re.S).group(1)))
stubs = sorted(names - implemented)
out = ["//! Generated by scripts/gen_cudnn_stubs.py: exports without an implementation.",
       "//! Each returns CUDNN_STATUS_NOT_SUPPORTED.",
       "#![allow(non_snake_case)]", "use crate::abi;", ""]
for n in stubs:
    out.append(f'#[unsafe(no_mangle)]\npub unsafe extern "system" fn {n}() -> i32 {{\n    abi::NOT_SUPPORTED\n}}\n')
(root / "crates/cudnn_shim/src/stubs.rs").write_text("\n".join(out))
print(f"{len(stubs)} stubs, {len(implemented)} implemented, {len(names)} total")
