#!/usr/bin/env python3
"""Generate crates/cublas_shim/src/stubs.rs: exported stubs returning
CUBLAS_STATUS_NOT_SUPPORTED (15) for every cuBLAS/cuBLASLt name that PyTorch's
CUDA DLLs import (cusolver, cusparse, torch_cuda) but the shim does not
implement. Windows resolves all imports at load, so the stand-in DLL must export
the full surface.

usage: gen_cublas_stubs.py imports.json   (list of names, or the pefile dump
{"cublas": [...], "cublasLt": [...]} of the genuine DLLs' exports)
Run from the repo root. Implemented names are skipped automatically.
"""
import json, re, sys, glob
d = json.load(open(sys.argv[1]))
names = set(d['cublas']) | set(d['cublasLt']) if isinstance(d, dict) else set(d)
impl = set()
for f in glob.glob('crates/cublas_shim/src/*.rs'):
    if f.endswith('stubs.rs'): continue
    impl |= set(re.findall(r'extern "(?:system|C)" fn (cublas\w+)', open(f).read()))
out = ['//! Generated by scripts/torch/gen_cublas_stubs.py. Do not edit.',
       '#![allow(non_snake_case)]', '']
for n in sorted(names - impl):
    if n.startswith('cublas'):
        out.append(f'#[unsafe(no_mangle)]\npub extern "system" fn {n}() -> i32 {{ 15 }}')
open('crates/cublas_shim/src/stubs.rs', 'w').write('\n'.join(out) + '\n')
print(len(out) - 3, 'stubs')
